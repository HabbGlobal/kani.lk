/**
 * `en` is `as const` so callers get literal-typed keys, but a translation must
 * be free to hold any string — otherwise `ta.ts` would have to repeat the
 * English text verbatim. This widens the leaves to `string` while keeping the
 * key structure exact, so a missing or misspelled key is still a build error.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

